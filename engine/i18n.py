_current=DEFAULT_UI


def set_ui_language(language):
    """Select the interface language. Unknown values fall back to English."""
    global _current
    _current=language if language in MESSAGES else DEFAULT_UI
    return _current


def ui_language():
    return _current


def t(key,**values):
    """Translate `key` in the current interface language."""
    table=MESSAGES.get(_current) or MESSAGES[DEFAULT_UI]
    text=table.get(key) or MESSAGES[DEFAULT_UI].get(key) or key
    try:return text.format(**values) if values else text
    except (KeyError,IndexError,ValueError):return text


def class_label(class_id,unknown_key='arena.class_unidentified'):
    table=CLASS_LABELS.get(_current) or CLASS_LABELS[DEFAULT_UI]
    return table.get(class_id) or t(unknown_key)


def card_language(setting,ui=None):
    """Resolve the card database locale from the stored setting."""
    if setting in CARD_CODES:return setting
    return CARD_FOR_UI.get(ui or _current,CARD_FOR_UI[DEFAULT_UI])


def card_language_name(code,ui=None):
    native=ui or _current
    for value,english,local in CARD_LANGUAGES:
        if value==code:return local if native=='zh-CN' else english
    return code


def language_index(code):
    for i,(value,_,_) in enumerate(CARD_LANGUAGES):
        if value==code:return i
    return 0
